use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum Language {
    English,
    Russian,
    Spanish,
    Portuguese,
    French,
    German,
    SimplifiedChinese,
    Hindi,
    Arabic,
}

impl Language {
    pub const ALL: [Self; 9] = [
        Self::English,
        Self::Russian,
        Self::Spanish,
        Self::Portuguese,
        Self::French,
        Self::German,
        Self::SimplifiedChinese,
        Self::Hindi,
        Self::Arabic,
    ];

    pub fn from_tag(tag: &str) -> Self {
        let normalized = tag.to_ascii_lowercase().replace('_', "-");
        match normalized.split('-').next().unwrap_or_default() {
            "ru" => Self::Russian,
            "es" => Self::Spanish,
            "pt" => Self::Portuguese,
            "fr" => Self::French,
            "de" => Self::German,
            "zh" => Self::SimplifiedChinese,
            "hi" => Self::Hindi,
            "ar" => Self::Arabic,
            _ => Self::English,
        }
    }

    pub fn tag(self) -> &'static str {
        match self {
            Self::English => "en",
            Self::Russian => "ru",
            Self::Spanish => "es",
            Self::Portuguese => "pt",
            Self::French => "fr",
            Self::German => "de",
            Self::SimplifiedChinese => "zh-Hans",
            Self::Hindi => "hi",
            Self::Arabic => "ar",
        }
    }

    pub fn native_name(self) -> &'static str {
        match self {
            Self::English => "English",
            Self::Russian => "Русский",
            Self::Spanish => "Español",
            Self::Portuguese => "Português",
            Self::French => "Français",
            Self::German => "Deutsch",
            Self::SimplifiedChinese => "简体中文",
            Self::Hindi => "हिन्दी",
            Self::Arabic => "العربية",
        }
    }
}

